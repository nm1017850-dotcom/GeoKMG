    $cIdx = 0
    foreach ($pat in $spec.claim_patterns) {
        $matchUnit = $nu | Where-Object { $_.quote -match $pat -and $_.kind -in @("paragraph", "example", "formula", "figure") } | Select-Object -First 1
        if (-not $matchUnit) {
            $matchUnit = $nu | Where-Object { $_.quote -match $pat } | Select-Object -First 1
        }
        if ($matchUnit) {
            $cIdx++
            $claims.Add([PSCustomObject]@{
                id                  = ("{0}-C{1:D2}" -f $nid, $cIdx)
                quote               = $matchUnit.quote
                page                = $matchUnit.page
                unit_id             = $matchUnit.id
                origin              = if ($matchUnit.kind -eq "figure_ocr") { "figure_ocr_description" } else { "ocr_markdown_unverified" }
                scan_check_required = ($matchUnit.status -ne "covered_in_node")
            })
        }
    }
    # Ensure every node has at least 2 claims (fallback to first substantial paragraphs/formulas if any regex missed)
    if ($claims.Count -lt 2) {
        $usedIds = @($claims | ForEach-Object { $_.unit_id })
        $fallbacks = @($nu | Where-Object { $_.kind -eq "paragraph" -and $_.id -notin $usedIds -and $_.quote.Length -gt 80 } | Select-Object -First (2 - $claims.Count))
        foreach ($fb in $fallbacks) {
